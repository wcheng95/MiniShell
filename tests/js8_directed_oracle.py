for code in range(32):
    print('    ' + json.dumps(commands[code]) + ',')
print('};\nstatic const struct call28_vector call28_vectors[] = {')
values = [0, 1, 262177559, 262177560, *sorted(base), 262177615, (1 << 28)-1]
