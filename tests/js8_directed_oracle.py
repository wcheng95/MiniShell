import hashlib
import json
from pathlib import Path
import re
import sys

assert len(sys.argv) == 3
for path, digest in zip(sys.argv[1:], (
    '2b4a877e7dae1a3fdd9141f4dd8af422185977d2e9363ad23ef6bc1918eaf53a',
    'dd7b8bf50466d0d2dc42b8c9ec05a72126363b3cd02c7492c5e2dcc9c9abb99d',
)):
    assert hashlib.sha256(Path(path).read_bytes()).hexdigest() == digest
source = re.sub(r'//[^\n]*', '', Path(sys.argv[1]).read_text())
base = dict((int(n) + 262177560, name) for name, n in re.findall(
    r'\{"([^"]+)",\s*nbasecall\s*\+\s*(\d+)\}', source))
assert len(base) == 54
cmd_block = source.split('QMap<QString, int> directed_cmds = {', 1)[1].split('};', 1)[0]
commands = {}
# QString ASCII key order: QMap::key returns the first matching key.
for name, code in sorted(re.findall(r'\{"([^"]*)",\s*(-?\d+)\}', cmd_block)):
    commands.setdefault(int(code), name)
assert set(range(32)) <= commands.keys()
alphabet = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ /@'


def pack_call(call):
    if call in base.values():
        return next(n for n, name in base.items() if name == call), 0
    portable = call.endswith('/P')
    call = call.removesuffix('/P')
    if call.startswith('3DA0'):
        call = '3D0' + call[4:]
    if call.startswith('3X') and 'A' <= call[2] <= 'Z':
        call = 'Q' + call[2:]
    permutations = [call]
    if 2 <= len(call) <= 5:
        permutations.append(' ' + call + ' ' * (5-len(call)))
    if 3 <= len(call) <= 5:
        permutations.append(call + ' ' * (6-len(call)))
    matched = None
    for word in permutations:
        match = re.search(r'([0-9A-Z ])([0-9A-Z])([0-9])([A-Z ])([A-Z ])([A-Z ])', word)
        if match:
            matched = match.group(0)
    assert matched is not None
    value = alphabet.index(matched[0])
    for i, radix in enumerate([36, 10, 27, 27, 27], 1):
        value = radix * value + alphabet.index(matched[i]) - (10 if i >= 3 else 0)
    return value, int(portable)


def unpack_call(value, portable):
    if value in base:
        return base[value]
    chars = []
    for _ in range(3):
        value, digit = divmod(value, 27)
        chars.append(alphabet[digit + 10])
    value, digit = divmod(value, 10)
    chars.append(alphabet[digit])
    value, digit = divmod(value, 36)
    chars.extend((alphabet[digit], alphabet[value]))
    call = ''.join(reversed(chars))
    if call.startswith('3D0'):
        call = '3DA0' + call[3:]
    if call.startswith('Q') and 'A' <= call[1] <= 'Z':
        call = '3X' + call[1:]
    return call.strip() + ('/P' if portable else '')


